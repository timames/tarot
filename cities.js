// True UTC offset (hours, east+) for an IANA zone at a given local birth
// date/time — DST and historical changes included, via the platform tzdb.
function cityUtcOffset(zone, dateStr, timeStr) {
  try {
    const probe = new Date(`${dateStr}T${timeStr || '12:00'}:00Z`);
    const fmt = new Intl.DateTimeFormat('en-US', { timeZone: zone, timeZoneName: 'longOffset' });
    const name = fmt.formatToParts(probe).find(p => p.type === 'timeZoneName').value;
    if (name === 'GMT') return 0;
    const m = name.match(/GMT([+-])(\d{1,2})(?::(\d{2}))?/);
    if (!m) return null;
    return (m[1] === '-' ? -1 : 1) * (parseInt(m[2], 10) + (m[3] ? parseInt(m[3], 10) / 60 : 0));
  } catch (e) {
    return null;
  }
}
